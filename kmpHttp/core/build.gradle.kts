import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    kotlin("multiplatform")
}

// Brings up the local HTTPS test server (test-server/) and emits Kotlin constants pointing at it, so
// the test suite depends on it instead of live httpbun.com / badssl.com. The server is a DETACHED
// daemon started idempotently by test-server/start.sh (it's left running across builds); this task
// just ensures it's up, then reads its LAN address + long-lived self-signed certs into TestServer.kt.
// Always re-runs so the address/certs stay in sync with whatever daemon is currently listening.
val testServerDir = rootDir.resolve("kmpHttp/test-server")
val testServerGenDir = layout.buildDirectory.dir("generated/testServer")
val startTestServer = tasks.register("startTestServer") {
    val outDir = testServerGenDir
    val serverDir = testServerDir
    outputs.dir(outDir)
    outputs.upToDateWhen { false }
    doLast {
        fun sh(command: String, workDir: java.io.File? = null): String {
            val proc = ProcessBuilder("bash", "-c", command)
                .directory(workDir)
                .redirectErrorStream(false)
                .start()
            val out = proc.inputStream.bufferedReader().readText().trim()
            val err = proc.errorStream.bufferedReader().readText().trim()
            val code = proc.waitFor()
            check(code == 0) { "command failed ($code): $command\n$err" }
            return out
        }

        // Idempotent: starts the detached server if it isn't already answering; writes server-info.json.
        logger.lifecycle(sh("./start.sh", serverDir))

        val info = serverDir.resolve("server-info.json").readText()
        fun field(re: String) = Regex(re).find(info)?.groupValues?.get(1)
            ?: error("test server info missing: $re in $info")
        val ip = field("\"ip\"\\s*:\\s*\"([^\"]+)\"")
        val httpsPort = field("\"httpsPort\"\\s*:\\s*(\\d+)")
        val mtlsPort = field("\"mtlsPort\"\\s*:\\s*(\\d+)")

        val certs = serverDir.resolve("certs").absolutePath
        val serverDer = sh("openssl x509 -in '$certs/server.crt' -outform der | base64 | tr -d '\\n'")
        val serverPin = "sha256/" + sh(
            "openssl x509 -in '$certs/server.crt' -pubkey -noout | openssl pkey -pubin -outform der " +
                "| openssl dgst -sha256 -binary | openssl base64 | tr -d '\\n'"
        )
        val clientP12 = sh("base64 < '$certs/client.p12' | tr -d '\\n'")
        val clientCertPem = sh("base64 < '$certs/client.crt' | tr -d '\\n'")
        val clientKeyPem = sh("base64 < '$certs/client.key' | tr -d '\\n'")

        val outFile = outDir.get().dir("kmphttp").asFile.resolve("TestServer.kt")
        outFile.parentFile.mkdirs()
        outFile.writeText(
            buildString {
                appendLine("package kmphttp")
                appendLine()
                appendLine("// GENERATED by :kmpHttp:core:startTestServer — do not edit. Points the test suite at the")
                appendLine("// local test-server/ daemon (LAN IP so the iOS simulator and Linux Docker runner reach it).")
                appendLine("// base64 values: server leaf DER, its SPKI pin, and the mutual-TLS client identity (p12/PEM).")
                appendLine("internal object TestServer {")
                appendLine("    const val host = \"$ip\"")
                appendLine("    const val baseUrl = \"https://$ip:$httpsPort\"")
                appendLine("    const val mtlsUrl = \"https://$ip:$mtlsPort\"")
                appendLine("    const val serverCertDer = \"$serverDer\"")
                appendLine("    const val serverPinSha256 = \"$serverPin\"")
                appendLine("    const val clientP12 = \"$clientP12\"")
                appendLine("    const val clientCertPem = \"$clientCertPem\"")
                appendLine("    const val clientKeyPem = \"$clientKeyPem\"")
                appendLine("    fun url(path: String): String = baseUrl + path")
                appendLine("}")
            }
        )
    }
}

kotlin {
    kmpHttpCommonConfig()

    jvm {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    withAppleTargets {
        binaries.framework {
            baseName = "kmpHttp"
            isStatic = true
        }
    }

    withLinuxTargets()

    applyDefaultHierarchyTemplate()

    sourceSets {
        /**
         * commonMain
         * ├── jvmMain
         * └── nonJvmMain
         *     └── nativeMain
         *         ├── appleMain (UrlSession engine)
         *         │   ├── iosMain
         *         │   └── macosMain ─┐
         *         ├── linuxMain ─────┤
         *         └── desktopMain <──┘  (libcurl engine; depends on :kmpHttp:curl)
         */
        val commonMain by getting
        val commonTest by getting {
            kotlin.srcDir(startTestServer)
            dependencies {
                // Test-scoped cycle on purpose (testing depends on core's main): the jar under
                // test lives there so it is not core's public surface.
                implementation(project(":kmpHttp:testing"))
            }
        }

        // Shared non-JVM code (native targets)
        val nonJvmMain by creating {
            dependsOn(commonMain)
            dependencies {
                implementation(Libs.Doist.normalizer)
            }
        }

        // Null-safe on hosts that configure no Kotlin/Native target (e.g. Windows): nativeMain is
        // only created by applyDefaultHierarchyTemplate when at least one native target exists.
        findByName("nativeMain")?.let { nativeMain ->
            nativeMain.dependsOn(nonJvmMain)

            // Desktop-native (linux + macos): the libcurl HTTP engine, built on the :curl wrapper.
            val desktopMain = create("desktopMain") {
                dependsOn(nativeMain)
                dependencies {
                    implementation(project(":kmpHttp:curl"))
                }
            }
            // Wire whichever desktop intermediates exist (depends on -PkmpTargets / host).
            listOf("macosMain", "linuxMain").forEach { name ->
                findByName(name)?.dependsOn(desktopMain)
            }
        }

        commonMain.dependencies {
            api(project(":kmpCommon")) // kmpcommon.io.AsyncSource/AsyncSink are part of the public API
            implementation(Libs.Kotlinx.coroutinesCore)
            implementation(Libs.Kotlinx.dateTime)
            implementation(Libs.Okio.core)
        }

        commonTest.dependencies {
            implementation(kotlin("test"))
            implementation(Libs.Kotlinx.coroutinesTest)
        }

        // Shared non-JVM test code (mirrors nonJvmMain: commonTest <- nonJvmTest <- nativeTest).
        val nonJvmTest by creating { dependsOn(commonTest) }
        findByName("nativeTest")?.dependsOn(nonJvmTest)

        // Desktop-native test source set: re-runs the shared SslTest against the explicit
        // CurlKmpHttpClient (so curl SSL is exercised on macOS too, not just Linux).
        val desktopTest by creating { dependsOn(commonTest) }
        listOf("macosTest", "linuxTest").forEach { name ->
            findByName(name)?.dependsOn(desktopTest)
        }

        jvmMain.dependencies {
            api(Libs.OkHttp.core)
        }
    }
}
// iOS/tvOS/watchOS simulator tests: Kotlin/Native defaults to `simctl spawn --standalone`, which runs
// the test binary OUTSIDE the simulator's launchd context — so `trustd` is unreachable and NSURLSession
// can't validate public certs (this is what broke the one system-default-trust SSL case). Instead boot
// the matching simulator and run the tests inside it (standalone = false), which makes trustd available.
fun bootFirstAvailableSimulator(deviceType: String): String {
    fun sh(cmd: String): String {
        val p = ProcessBuilder("bash", "-c", cmd).redirectErrorStream(true).start()
        val out = p.inputStream.bufferedReader().readText().trim()
        p.waitFor()
        return out
    }
    val udid = sh("xcrun simctl list devices available | grep -F '$deviceType' | head -1 | grep -oiE '[0-9a-f-]{36}'")
    require(udid.isNotEmpty()) { "no available '$deviceType' simulator to run the tests" }
    // Idempotent: boot if shut down, then wait until services (incl. trustd) are up.
    sh("xcrun simctl boot '$udid' 2>/dev/null; xcrun simctl bootstatus '$udid' 2>/dev/null")
    return udid
}

// Only matches when Apple simulator targets are configured (i.e. on a macOS host); on Linux there are
// no such tasks, so this block — and any `xcrun` call — never runs. The device UDID is supplied as a
// lazy provider so the boot happens at task execution, not during configuration.
tasks.withType<org.jetbrains.kotlin.gradle.targets.native.tasks.KotlinNativeSimulatorTest>().configureEach {
    standalone.set(false)
    val deviceType = when {
        name.startsWith("watchos") -> "Apple Watch"
        name.startsWith("tvos") -> "Apple TV"
        else -> "iPhone"
    }
    device.set(providers.provider { bootFirstAvailableSimulator(deviceType) })
}
